EN7 = r'''
You have decided to stop. Day one is over, or it starts now. And you are wondering: what is this week going to be like?

Honest answer: hard, a lot of the time. And long. A day can feel like three. A week can feel like a month.

This page walks through the first seven days. What you might run into, what is normal, and what to do. Everyone is different, but these are the things many people describe.

## Day 1: the decision itself

The first day is often strange. Not because something big happens, but because nothing does. You expected a dramatic moment. Instead you get up, go to work and go to bed.

That is exactly where the risk is. Without locks in place, day one is full of moments where your hand reaches for your phone out of habit. Not even because you want to. Just habit.

What to do on day 1:

- **Make it hard.** Sign up to GamStop, install a blocker on your phone and laptop, and turn on your bank's gambling block. [How to block gambling sites, apps and bank payments](https://afterbetting.com/blog/block-gambling-sites-and-payments) shows you how.
- **Delete every gambling app.** Including the sports apps with odds.
- **Write three lines to yourself.** Why you are doing this, who for, what you hope for a year from now. Keep it somewhere. You will read it again later this week.

## Days 2 and 3: the quiet gets loud

This is where you start to feel it. Your head is restless. You find it hard to sit still for ten minutes. Your phone keeps pulling at you.

Many people describe things like:

- worse sleep,
- irritability over small things,
- feeling flat or on edge,
- craving sugar, coffee or other quick hits.

This is common in the first days after stopping, and for most people it eases.

What to do on days 2 and 3:

- **Move.** A long walk, the gym, a bike ride. Anything that gets you out of your head and out of the house.
- **Eat proper meals.** Not just coffee and snacks.
- **Plan the evening.** If you used to gamble at night, those are the hours to fill. For me it was evenings and weekends, the times without work and without a plan.

## Day 4: the first real urge

Somewhere around day four or five, many people get the first big urge. Not a passing thought. A wave. Your heart beats faster, your hand goes for your phone, and your head finds reasons why once would be fine.

That is not failure. It is the habit pushing back.

What to do:

- **Delay it.** Set a timer for 15 minutes. You do not have to win forever, just this quarter of an hour.
- **Change where you are.** Stand up, go to another room, go outside.
- **Call someone.** A friend, or the National Gambling Helpline on 0808 8020 133. It is free and open 24/7.
- **Drink some water, eat something.** Hunger and tiredness make urges stronger.

Urges usually rise, peak and fall. More on getting through them in [Do gambling urges go away?](https://afterbetting.com/blog/do-gambling-urges-go-away)

The free recovery kit in the app has short exercises for exactly this moment, with a timer and the helpline one tap away.

## Days 5 and 6: the emptiness

Around day five or six, something shifts. The restlessness may ease a little. Sleep can get a bit better.

But something else often comes in its place: an empty feeling. Boredom that is not quite boredom. And from that emptiness comes a dangerous thought: "I have done the hard part. Once would be fine now."

This is one of the riskiest moments of the week.

What to do:

- **Fill your time on purpose.** Plan your evenings and the weekend. Make plans with people. [What to do instead of gambling](https://afterbetting.com/blog/what-to-do-instead-of-gambling) has ideas.
- **Write a few lines each night.** What was hard, what went well. It sounds small. It helps you see what is going on in your head.
- **Read what you wrote on day one.** Remind yourself why.

## Day 7: one week

One week. It sounds small. It is not.

It is proof that you can go a week without gambling. That the world did not end. That the urges came and you got through them.

On day seven:

- you have probably got through at least one real urge,
- you have money you would otherwise have lost. Count it,
- you know a bit more about your own risky moments.

Mark it. Nothing big. Something real. Buy yourself something small, with money that is actually there now.

## If you slipped this week

Then you are not back at zero. Look at what happened, close the gap you went through and start again today. [What to do right after a gambling relapse](https://afterbetting.com/blog/what-to-do-after-gambling-relapse) walks you through it.

## What comes after the first week

The first week is often the most intense. The weeks after are a different kind of work: filling the gap, building a rhythm, dealing with the money. For what weeks two to four tend to look like, read [The first 30 days without gambling](https://afterbetting.com/blog/first-30-days-without-gambling).

For now: one day at a time. Today counts.
'''

